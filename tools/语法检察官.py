    for i, p in enumerate(paras):
        if re.match(r"^\*{0,2}(课前测第\d题|例题\d|随堂练习题\d)\*{0,2}$", p):
            prev = paras[i - 1] if i else ""
            ok = len(prev) < 46 and any(
                k in prev for k in ["第一", "第二", "第三", "第四", "第五", "最后",
                                    "接下来", "先看", "来看", "接着", "我们先"])
            if not ok:
                no_lead.append(p.strip("*"))
    if no_lead:
        issues.append(f"【衔接】{len(no_lead)} 道题前没有口语衔接语：{', '.join(no_lead[:4])}")
    else:
        passes.append("题目衔接：14 道题全部有衔接语")

    # ── 7 答案先于推理 ──
    早报 = []
    for i, p in enumerate(paras):
        if re.match(r"^\*{0,2}(课前测第\d题|例题\d|随堂练习题\d)", p):
            # 题号后第 2 段（跳过题干/选项）若已出现答案，判定为先报答案
            seg = paras[i + 1:i + 4]
            for j, sp in enumerate(seg):
                if sp.startswith("题目：") or re.match(r"^A[.、]", sp):
                    continue
                if re.search(r"(答案是|这道题的答案|正确答案)", sp) and j <= 1:
                    早报.append(p.strip("*"))
                break
    if 早报:
        issues.append(f"【先报答案】{len(早报)} 处一上来就给结论：{', '.join(早报[:4])}")
    else:
        passes.append("讲题顺序：先推理后答案")

    # ── 8 互动密度 ──
    ic = sum(t.count(k) for k in INTERACT)
    per_k = ic / max(total_zh, 1) * 1000
    if per_k < TH["互动密度_每千字"]:
        issues.append(f"【互动不足】互动标记密度 {per_k:.1f}/千字，低于 " + str(TH["互动密度_每千字"]) + "。讲解偏念稿")
    elif per_k < TH["互动密度_目标"]:
        warns.append(f"互动密度 {per_k:.1f}/千字，偏低（建议 ≥{TH['互动密度_目标']}）")
    else:
        passes.append(f"互动密度：{per_k:.1f}/千字")

    # 逐题互动检查
    weak = []
    blocks = re.split(r"\*{0,2}(?:课前测第\d题|例题\d|随堂练习题\d)\*{0,2}", t)
    for idx, b in enumerate(blocks[1:], 1):
        b = b[:1400]
        n = sum(b.count(k) for k in INTERACT)
        if n < TH["逐题互动_每题最少"]:
            weak.append(f"第{idx}块({n})")
    if weak:
        issues.append(f"【互动不足】{len(weak)} 道题的讲评互动标记少于 2 个：{', '.join(weak[:6])}")
    elif not weak:
        passes.append("逐题互动：每道题讲评均有互动")

    # ── 9 丝滑度：段落连接词 ──
    body = [p for p in paras if len(p) > 12 and not p.startswith("题目：")
            and not re.match(r"^\*{0,2}(答案|解析|课前测|例题|随堂)", p)]
    linked = sum(1 for p in body if any(p.startswith(cw) for cw in CONNECT))
    ratio = linked / max(len(body), 1) * 100
    if ratio < TH["段落承接率"]:
        issues.append(f"【不够丝滑】仅 {ratio:.0f}% 的段落有承接词开头，段与段是硬切")
    elif ratio < TH["段落承接率_目标"]:
        warns.append(f"段落承接率 {ratio:.0f}%，可再加连接词")
    else:
        passes.append(f"段落承接率：{ratio:.0f}%")

    # ── 10 句长：书面化检测 ──
    sents = [s for s in re.split(r"[。！？]", t) if zh(s) > 0]
    avg = sum(zh(s) for s in sents) / max(len(sents), 1)
    long_n = sum(1 for s in sents if zh(s) > TH["超长句_字数线"])
    if avg > TH["平均句长_上限"]:
        issues.append(f"【书面化】平均句长 {avg:.0f} 字，偏长。口播稿应多用短句")
    elif avg > TH["平均句长_目标"]:
        warns.append(f"平均句长 {avg:.0f} 字，可再断碎一些")
    else:
        passes.append(f"平均句长：{avg:.0f} 字")
    if long_n > TH["超长句_上限句数"]:
        warns.append(f"{long_n} 句超过 55 字，建议拆开")

    # ── 11 讲义腔：长段落里没有一个「你我咱」，就是在自说自话不是在对人讲 ──
    ADDR = ("你", "我", "咱", "同学")
    lecture = []
    for p in paras:
        if zh(p) < 30:
            continue
        if p.startswith(("题目", "答案", "解析")) or re.match(r"^\*{0,2}(课前测|例题|随堂)", p):
            continue
        if any(a in p for a in ADDR):
            continue
        if any(k in p for k in INTERACT):
            continue
        # 口语语气词：带了就说明是在说话，不是在写条文
        if any(k in p for k in ("吧", "呢", "啊", "嘛", "咯", "行了", "就完了",
                                "而已", "对了", "得了", "着呢", "才对")):
            continue
        lecture.append(p)
    rate = len(lecture) / max(len([p for p in paras if zh(p) >= 30]), 1) * 100
    if rate > 18:
        issues.append(f"【讲义腔】{len(lecture)} 个长段落通篇没有「你/我/咱」，占 {rate:.0f}%，"
                      f"是在自说自话不是在对人讲\n            例：{lecture[0][:40]}…")
    elif rate > 10:
        warns.append(f"讲义腔段落占 {rate:.0f}%，可再加对学生说话的口气")
    else:
        passes.append(f"讲义腔：仅 {rate:.0f}%")

    # ── 12 推理跳步：针对具体单词下判断，却不给依据 ──
    VERDICT = ("是谓语", "是宾语", "是表语", "是宾补", "是宾语补足语",
               "是系动词", "是双宾语", "就它", "就是谓语", "就是系动词")
    GROUND = ("因为", "所以", "说明", "既然", "带着", "变过形", "定时态", "过去式",
              "三单", "带时态", "它自己", "干的活", "换成", "连起来", "承受", "落在",
              "两点", "后面跟", "后面接", "位置", "拎出来", "挂着", "补一块", "补完",
              "变成是", "口味", "本身", "意思", "整句", "时态就是", "看不出", "长成",
              "先判断", "标记", "谓语后面", "能看出", "不参与", "结构完整", "意思没变", "看它后面", "没有宾语", "介词短语")
    jump = []
    for i, p in enumerate(paras):
        if zh(p) > 34 or zh(p) < 2 or p.endswith("？"):
            continue
        if p.startswith(("题目", "答案", "解析")):
            continue
        if not re.search(r"[A-Za-z]{3,}", p):      # 必须是在judge一个具体英文词
            continue
        if any(v in p for v in VERDICT) and not any(g in p for g in GROUND):
            jump.append(p)
    if len(jump) >= 1:
        issues.append(f"【推理跳步】{len(jump)} 处对具体单词直接下判断没给依据，"
                      f"听着像背结论\n            例：{jump[0][:40]}…")
    else:
        passes.append("推理链：判断都有依据")

    # ── 13 时态含糊：说了「带时态」却不说是哪个时态 ──
    TENSES = ("一般现在时", "一般过去时", "一般将来时", "现在进行时", "过去进行时",
              "现在完成时", "过去完成时", "现在完成进行时", "过去将来时",
              "被动语态", "过去式", "过去分词", "三单", "原形")
    vague = []
    for i, p in enumerate(paras):
        if "带时态" not in p and "带着时态" not in p:
            continue
        # 泛指规则的表述（没提具体单词）不算含糊，只有针对某个词下判断时才要求点明
        if not re.search(r"[A-Za-z]{3,}", p):
            continue
        # 说「不带时态、是非谓语」时无须点明具体时态——本来就没有时态
        if "不带时态" in p or "非谓语" in p:
            continue
        window = "".join(paras[max(0, i - 2):i + 3])
        if not any(t in window for t in TENSES):
            vague.append(p[:44])
    if vague:
        issues.append(f"【时态含糊】{len(vague)} 处只说「带时态」却没说是哪个时态。"
                      f"学生不认识时态就跟不上\n            例：{vague[0]}…")
    else:
        passes.append("时态说明：均已点明具体时态")

    # ── 14 段落憋气：单段过长，主播一口气念不完 ──
    long_p = [p for p in paras
              if zh(p) > TH.get("单段字数上限", 60)
              and not p.startswith(("题目", "答案", "解析"))
              and not re.match(r"^A[.、]", p)]
    if len(long_p) > 0:
        issues.append(f"【段落憋气】{len(long_p)} 个段落超过 "
                      f"{TH.get('单段字数上限', 60)} 字，主播一口气念不完，"
                      f"必须拆开\n            例：{long_p[0][:44]}…")
    else:
        passes.append("段落长度：无憋气段")

    # ── 15 逻辑闭环：开场承诺是否兑现、告别语是否只出现一次 ──
    head = "".join(paras[:16])
    tail_txt = "".join(paras[-26:])
    loop = []
    # 开场抛出的关键词，结尾必须回扣
    for kw in ("语法填空", "高考", "下节课", "白送"):
        if kw in head and kw not in tail_txt and kw != "下节课":
            loop.append(f"开场提到「{kw}」，结尾没有回扣，承诺落空")
    # 告别语只能出现在最后
    byes = [i for i, p in enumerate(paras) if re.search(r"下节课(我们讲|见)", p)]
    if byes and byes[0] < len(paras) - 22:
        loop.append(f"告别语出现在第 {byes[0]} 段（全文共 {len(paras)} 段），"
                    f"说完再见又继续讲课，等于告了两次别")
    # 说了「下节课再讲」却在本课大讲特讲
    for m in re.finditer(r"([\u4e00-\u9fff]{2,8})[^。]{0,20}下节课[^。]{0,14}(展开|细讲|再讲)", t):
        term = m.group(1)
        after = t[m.end():]
        if after.count(term) > 8:
            loop.append(f"说了「{term}下节课再展开」，可本课后文又出现 {after.count(term)} 次，自相矛盾")
            break
    if loop:
        for x in loop:
            issues.append(f"【逻辑不闭环】{x}")
    else:
        passes.append("逻辑闭环：开场承诺已兑现，收尾干净")

    # ── 16 节奏平板：长时间没有短句，念出来像匀速念稿 ──
    rb = [p for p in paras if not p.startswith(("题目", "答案", "解析"))
          and not re.match(r"^\*{0,2}(课前测|例题|随堂|A[.、])", p)]
    lens = [zh(p) for p in rb]
    shorts = [i for i, x in enumerate(lens) if x < 10]
    ratio_s = len(shorts) / max(len(lens), 1) * 100
    gap = max([shorts[i + 1] - shorts[i] for i in range(len(shorts) - 1)] or [len(lens)])
    if ratio_s < 8 or gap > 26:
        issues.append(f"【节奏平板】短句仅占 {ratio_s:.0f}%，最长 {gap} 段没有一句短句。"
                      f"念出来是匀速念稿，没有起伏\n            "
                      f"每隔十几段要甩一句短的当气口：「停。」「不通。」「完不成。」")
    elif ratio_s < 11 or gap > 20:
        warns.append(f"节奏偏平：短句占 {ratio_s:.0f}%，最长无停顿区 {gap} 段")
    else:
        passes.append(f"节奏：短句占 {ratio_s:.0f}%，最长无停顿区 {gap} 段")

    # ── 17 时长：单条视频，上限按内容量分级 ──
    wpm = TH.get("口播每分钟字数", 250)
    mins = total_zh / wpm
    # 本节涵盖几个知识主题：数正文里的「先说X」「说完X，我们说Y」「最后说Z」
    # 主题数 = 正文里的教学板块数。按几类转场标记统计，取去重后的段落位置
    marks = set()
    for m in re.finditer(r"(先说[一-鿿]{1,4}|说完[一-鿿]{1,4}我们说|最后说[一-鿿]{1,4}|"
                         r"下面这块|接下来说|老师教大家第[一二三四]个|"
                         r"这里有三条判断标准|那这十类词|知道有十类词还不够|"
                         r"我们再说|接着我们说|下面我们讲)", t):
        marks.add(m.start() // 900)      # 900 字为一格，避免同一板块重复计数
    topics = max(1, min(len(marks), 4))
    cap = {1: 20, 2: 28, 3: 36, 4: 42}[topics]
    if mins > cap:
        issues.append(f"【时长超标】全文 {total_zh} 字约 {mins:.0f} 分钟，"
                      f"本节含 {topics} 个知识主题，上限 {cap} 分\n            "
                      f"先砍：重复的例子、旁支知识点、讲了两遍的道理。"
                      f"砍不动说明主题本身太多，只能在讲解密度上取舍")
    elif mins < 10:
        warns.append(f"时长偏短：约 {mins:.0f} 分钟，讲解可能不够透")
    else:
        passes.append(f"时长：约 {mins:.0f} 分（{topics} 个主题，上限 {cap} 分）")

    # ── 18 缺做题缓冲：读完题直接开讲，学生没机会动笔 ──
    PAUSE = tuple(set(("暂停", "先写", "写完", "写好", "圈好", "圈完", "圈出", "圈一个",
             "划一遍", "先自己做", "先自己写", "先自己圈", "先自己找", "先自己选",
             "先自己判断", "想二十秒", "想十秒", "想五秒", "先做", "选好", "多给自己",
             "自己划") + tuple(LAW.get("停顿词表", []))))
    noBuf = []
    for i, p in enumerate(paras):
        if not re.match(r"^\*{0,2}(课前测第\d题|例题\d|随堂练习题\d)\*{0,2}$", p):
            continue
        seg = "".join(paras[i + 1:i + 6])
        if not any(k in seg for k in PAUSE):
            noBuf.append(p.strip("*"))
    if len(noBuf) > 0:
        issues.append(f"【缺做题缓冲】{len(noBuf)} 道题读完就开讲，"
                      f"没给学生动笔的时间\n            "
                      f"{'、'.join(noBuf[:5])}　"
                      f"要先说「你暂停一下，写在纸上，写完再继续」，再回来讲")
    else:
        passes.append("做题缓冲：每道题都留了动笔时间")

    # ── 19 出题质量：答案重复 / 选项分布 / 争议词 / 超纲后缀 ──
    ansList = []
    for m in re.finditer(r"所以(?:这儿|这个空|这道题|两个空分别)?(?:就)?(?:填|选)\s*"
                         r"((?:to |be )?[A-Za-z]+(?:\s*和\s*(?:to |be )?[A-Za-z]+)?|[A-D])", t):
        for w in re.split(r"\s*和\s*", m.group(1)):
            ansList.append(w)
    fill = [a for a in ansList if len(a) > 1]
    pick = [a for a in ansList if len(a) == 1 and a.isalpha()]

    dup = [x for x in set(fill) if fill.count(x) > 1]
    if dup:
        issues.append(f"【出题·答案重复】{'、'.join(dup)} 在多道题里重复作答案，"
                      f"等于白出一道题")
    if len(pick) >= 3 and len(set(pick)) == 1:
        issues.append(f"【出题·选项分布】{len(pick)} 道选择题答案全是 {pick[0]}，必须打散")

    # 争议词：本身就有多重词性，拿来问词性会有歧义
    AMBI = {"well": "既是副词也是形容词", "fast": "形容词副词同形",
            "hard": "形容词副词同形", "late": "形容词副词同形",
            "early": "形容词副词同形", "high": "形容词副词同形",
            "near": "形容词副词同形", "long": "形容词副词同形"}
    for w, why in AMBI.items():
        if re.search(rf"(划线单词|单词)\s*{w}\s*属于哪一类词", t):
            issues.append(f"【出题·争议题】拿 {w} 问词性有歧义（{why}），"
                          f"学生答另一个你驳不回。换一个只有唯一解读的词")

    # 超纲：本课没教的后缀却要学生变形
    taught = set(re.findall(r"[-—]?\b(tion|sion|ment|ness|ity|ance|ence|ful|less|ous|"
                            r"able|ive|al|ly|ize|ify|en|ate)\b", t))
    IRREG = {"ability": "able→ability 是不规则变化",
             "length": "long→length 是不规则变化",
             "strength": "strong→strength 是不规则变化",
             "width": "wide→width 是不规则变化",
             "depth": "deep→depth 是不规则变化",
             "height": "high→height 是不规则变化"}
    for w, why in IRREG.items():
        if w in fill and "不规则" not in t:
            issues.append(f"【出题·超纲】答案 {w} 属于不规则变化（{why}），"
                          f"课上只讲了规则后缀，学生推不出来")

    if not dup and not (len(pick) >= 3 and len(set(pick)) == 1):
        passes.append(f"出题质量：答案无重复，选项分布 {'/'.join(sorted(set(pick))) or '—'}")

    # ── 20 例句重复：同一个英文例句在不同板块各讲一遍 ──
    # 先给每个位置标出它属于哪个板块（题号之间为一段）
    marks = [(m.start(), m.group(0)) for m in
             re.finditer(r"\*{0,2}(?:课前测第\d题|例题\d|随堂练习题\d)\*{0,2}", t)]

    # 板块编号：每个题号开一个新块；块内若出现「课前测结束」等正文起点，再开一块
    breaks = sorted([m.start() for m in
                     re.finditer(r"\*{0,2}(?:课前测第\d题|例题\d|随堂练习题\d)\*{0,2}|"
                                 r"课前测(?:全部)?结束|方法讲完了|道理都讲完了|"
                                 r"我们先说|说完主语|接下来是今天最重要", t)])

    def block_of(pos):
        b = 0
        for k, st in enumerate(breaks, 1):
            if pos >= st:
                b = k
        return b

    sents = {}
    for m in re.finditer(r"[A-Z][A-Za-z'’,\. ]{16,80}[\.。]", t):
        words = re.sub(r"[^A-Za-z ]", " ", m.group(0)).split()
        if len(words) < 6:
            continue
        key = " ".join(w.lower() for w in words[:6])   # 前六个词做指纹
        if key.split()[0] in ("a", "b", "c", "d"):
            continue
        sents.setdefault(key, []).append(m.start())

    CALLBACK = ("刚才", "上面", "前面", "还记得", "第一题", "第二题", "第三题",
                "第四题", "第五题", "第六题", "刚学", "我们说过", "提过")
    reused = []
    for key, pos in sents.items():
        blocks = {block_of(x) for x in pos}
        if len(blocks) < 2:
            continue
        # 明确回指前面某道题的引用是正当的，放行
        ctx = t[max(0, pos[-1] - 70):pos[-1]]
        if any(c in ctx for c in CALLBACK):
            continue
        reused.append(key)
    if reused:
        issues.append(f"【例句重复】{len(reused)} 个英文例句跨板块重复出现，"
                      f"又没说明是在回指前面\n            例：{reused[0][:50]}…")
    else:
        passes.append("例句：无跨板块重复")

    # ── 21 格式残留 ──
    for bad, why in [("|", "疑似表格残留"), ("•", "项目符号"), ("- ", "列表符号")]:
        if bad in t and t.count(bad) > 3:
            warns.append(f"疑似 {why}：出现 {t.count(bad)} 次「{bad}」")

    return name, total_zh, issues, warns, passes



