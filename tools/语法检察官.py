def cross_check():
    """把所有课放在一起查：套话逐字重复、例句跨课复用"""
    import glob as _g
    print("\n" + "═" * 68)
    print("  跨课查重　　单节合格 ≠ 整套课不重复")
    print("═" * 68)
    files = sorted(_g.glob(os.path.join(DOCS, "*.docx")))
    if len(files) < 3:
        print("  课程不足三节，暂不需要跨课查重。\n"); return 0
    texts = {}
    for f in files:
        m = re.search(r"第(\d+)课", f)
        texts[m.group(0) if m else f] = extract(f)
    total = len(texts)
    bad = 0

    # ① 套话逐字重复：长度 ≥10 的整句，在半数以上课里原样出现
    sent_hit = {}
    for name, t in texts.items():
        for line in t.split("\n"):
            line = line.strip()
            if 10 <= zh(line) <= 40 and not line.startswith(("题目", "**", "A.")):
                sent_hit.setdefault(line, set()).add(name)
    dup = [(l, s_) for l, s_ in sent_hit.items() if len(s_) > total / 2]
    dup.sort(key=lambda x: -len(x[1]))
    if dup:
        bad += 1
        print(f"\n  ✗ 套话重复：{len(dup)} 句在半数以上课里逐字出现")
        for l, s_ in dup[:8]:
            print(f"      {len(s_)}/{total} 课　「{l[:38]}」")
        print("      学生连着看会觉得是模板拼的。每节换一套说法。")
    else:
        print("\n  ✓ 套话：无半数以上课的逐字重复")

    # ② 例句跨课复用
    fp = {}
    for name, t in texts.items():
        for m in re.finditer(r"[A-Z][A-Za-z'’,\. ]{18,90}[\.。]", t):
            w = re.sub(r"[^A-Za-z ]", " ", m.group(0)).split()
            if len(w) < 7:
                continue
            k = " ".join(x.lower() for x in w[:7])
            fp.setdefault(k, set()).add(name)
    reuse = [(k, v) for k, v in fp.items() if len(v) > 1]
    if reuse:
        bad += 1
        print(f"\n  ✗ 例句跨课复用：{len(reuse)} 个句子在不同课里出现")
        for k, v in reuse[:6]:
            print(f"      {sorted(v)}　{k[:44]}")
    else:
        print("  ✓ 例句：无跨课复用")

    # ③ 各课时长离散度
    lens = {n: zh(t) / TH.get("口播每分钟字数", 250) for n, t in texts.items()}
    lo, hi = min(lens.values()), max(lens.values())
    if hi > lo * 2:
        bad += 1
        print(f"\n  ✗ 时长不齐：最短 {lo:.0f} 分，最长 {hi:.0f} 分，相差一倍以上")
        for n, v in sorted(lens.items(), key=lambda x: -x[1])[:3]:
            print(f"      {n}  {v:.0f} 分")
        print("      同一套课时长差太多，体例不统一。")
    else:
        print(f"  ✓ 时长：{lo:.0f} 到 {hi:.0f} 分，离散度可接受")


    # ④ 术语清单跨课一致性：同一组词，各课列的不能差
    # 每组配一个「主题词」：正文里出现该主题词，才算这节课真在讲这一组
    GROUPS = {
        "感官系动词": (["look", "sound", "taste", "smell", "feel"], "感官"),
        "使役动词": (["make", "let", "have"], "使役动词"),
        "无被动的不及物动词": (["happen", "appear", "arrive", "rise", "belong"], "不及物动词"),
        "并列连词": (["and", "but", "or", "so"], "并列连词"),
    }
    miss = []
    for gname, (words, topic) in GROUPS.items():
        cover = {}
        for name, t in texts.items():
            if topic not in t:                      # 这节课压根没讲这一组，跳过
                continue
            hit = [w for w in words if re.search(rf"\b{w}\b", t)]
            if len(hit) >= 3:                       # 至少列了三个，才算在系统介绍
                cover[name] = set(hit)
        if len(cover) < 2:
            continue
        full = max(cover.values(), key=len)
        for name, hit in cover.items():
            lack = full - hit
            if lack:
                miss.append(f"{gname}：{name} 少了 {'、'.join(sorted(lack))}")
    if miss:
        bad += 1
        print(f"\n  ✗ 术语清单不一致：{len(miss)} 处")
        for x in miss[:8]:
            print("      " + x)
        print("      同一组词各课列的不一样，学生会问「这个哪儿冒出来的」。")
    else:
        print("  ✓ 术语清单：各课口径一致")

    print("\n" + "═" * 68)
    print(f"  跨课查重：{'全部通过' if not bad else str(bad) + ' 类问题'}")
    print("═" * 68 + "\n")
    return bad


def watch():
    """守候模式：监听源码改动，一改就自动审查修正"""
    print("\n守候中……源码一有改动就自动审查修正。Ctrl+C 退出。\n")
    seen = {}
    for _, js in lessons():
        seen[js] = os.path.getmtime(js)
    while True:
        try:
            time.sleep(2)
            for n, js in lessons():
                mt = os.path.getmtime(js)
                if seen.get(js) != mt:
                    seen[js] = mt
                    print(f"\n检测到改动：{os.path.basename(js)}")
                    run([n])
                    seen[js] = os.path.getmtime(js)
        except KeyboardInterrupt:
            print("\n已退出守候。\n"); return


